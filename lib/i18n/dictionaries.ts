export type ErrorCode = keyof Dictionary['errors']

export function errorMessage(dict: Dictionary, code: unknown) {
  return typeof code === 'string' && code in dict.errors
    ? dict.errors[code as ErrorCode]
    : dict.errors.GENERIC
}


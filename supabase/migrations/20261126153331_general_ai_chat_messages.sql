create table public.general_ai_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  body text not null check (char_length(body) between 1 and 1000000),
  created_at timestamptz not null default now()
);

create index general_ai_messages_user_id_id_idx
  on public.general_ai_messages (user_id, id desc);

alter table public.general_ai_messages enable row level security;
revoke all on table public.general_ai_messages from anon, authenticated;
grant select, insert, update, delete on table public.general_ai_messages to service_role;
grant usage, select on sequence public.general_ai_messages_id_seq to service_role;
